/// Vector icons of the share sheet, from the design's SVGs (absolute M/L/H/V/C/Z path data only).
enum PostShareIcons {
    static func instagram(color: UIColor) -> UIImage? {
        return self.image(size: CGSize(width: 18.0, height: 18.0), paths: [instagramOutline, instagramLens, instagramDot], color: color)
    }

    static func x(color: UIColor) -> UIImage? {
        return self.image(size: CGSize(width: 18.0, height: 18.0), paths: [xLogo], color: color)
    }

    static func threads(color: UIColor) -> UIImage? {
        return self.image(size: CGSize(width: 18.0, height: 18.0), paths: [threadsLogo], color: color)
    }

    static func reddit(color: UIColor) -> UIImage? {
        return self.image(size: CGSize(width: 20.0, height: 20.0), paths: [redditLogo], color: color)
    }

    /// The Telegram plane, 19 x 15 at its natural size.
    static let telegramLogoSize = CGSize(width: 19.0, height: 15.0)

    static func drawTelegramLogo(in context: CGContext, frame: CGRect, color: UIColor) {
        guard let path = self.path(telegramLogo) else {
            return
        }
        context.saveGState()
        context.translateBy(x: frame.minX, y: frame.minY)
        context.scaleBy(x: frame.width / self.telegramLogoSize.width, y: frame.height / self.telegramLogoSize.height)
        context.addPath(path)
        context.setFillColor(color.cgColor)
        context.fillPath()
        context.restoreGState()
    }

    private static func image(size: CGSize, paths: [String], color: UIColor) -> UIImage? {
        let cgPaths = paths.compactMap { self.path($0) }
        if cgPaths.count != paths.count {
            return nil
        }
        return UIGraphicsImageRenderer(size: size).image { rendererContext in
            let context = rendererContext.cgContext
            context.setFillColor(color.cgColor)
            for path in cgPaths {
                context.addPath(path)
                context.fillPath()
            }
        }
    }

    /// Parses absolute SVG path data (M, L, H, V, C, Z, with implicit repeats). Returns nil on anything else.
    private static func path(_ data: String) -> CGPath? {
        let path = CGMutablePath()
        let scalars = Array(data.unicodeScalars)
        var index = 0
        var command: Character?
        var current = CGPoint()

        func skipSeparators() {
            while index < scalars.count, scalars[index] == " " || scalars[index] == "," || scalars[index] == "\n" || scalars[index] == "\t" {
                index += 1
            }
        }

        func readNumber() -> CGFloat? {
            skipSeparators()
            let start = index
            if index < scalars.count, scalars[index] == "-" || scalars[index] == "+" {
                index += 1
            }
            var seenPoint = false
            while index < scalars.count {
                let scalar = scalars[index]
                if scalar >= "0" && scalar <= "9" {
                    index += 1
                } else if scalar == "." && !seenPoint {
                    seenPoint = true
                    index += 1
                } else {
                    break
                }
            }
            guard index > start, let value = Double(String(String.UnicodeScalarView(scalars[start ..< index]))) else {
                return nil
            }
            return CGFloat(value)
        }

        while true {
            skipSeparators()
            if index >= scalars.count {
                break
            }
            let scalar = scalars[index]
            if CharacterSet.letters.contains(scalar) {
                command = Character(scalar)
                index += 1
                if command == "Z" {
                    path.closeSubpath()
                    command = nil
                }
                continue
            }
            switch command {
            case "M", "L":
                guard let x = readNumber(), let y = readNumber() else {
                    return nil
                }
                current = CGPoint(x: x, y: y)
                if command == "M" {
                    path.move(to: current)
                    // Further pairs after a moveto are implicit linetos.
                    command = "L"
                } else {
                    path.addLine(to: current)
                }
            case "H":
                guard let x = readNumber() else {
                    return nil
                }
                current = CGPoint(x: x, y: current.y)
                path.addLine(to: current)
            case "V":
                guard let y = readNumber() else {
                    return nil
                }
                current = CGPoint(x: current.x, y: y)
                path.addLine(to: current)
            case "C":
                guard let x1 = readNumber(), let y1 = readNumber(), let x2 = readNumber(), let y2 = readNumber(), let x = readNumber(), let y = readNumber() else {
                    return nil
                }
                current = CGPoint(x: x, y: y)
                path.addCurve(to: current, control1: CGPoint(x: x1, y: y1), control2: CGPoint(x: x2, y: y2))
            default:
                return nil
            }
        }
        return path
    }
}

